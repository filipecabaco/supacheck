#!/usr/bin/env elixir
# Render rule templates into labelled training/eval data.
#
#   elixir scripts/gen_dataset.exs [--out data/generated] [--val-frac 0.1]
#
# Splits:
#   test  = unseen tables (resources with split: :test) + one held-out template family per rule
#   val   = deterministic ~10% of the rest
#   train = everything else
# Outputs per split: heads format (one row per rule decision) and typed format
# ({state, questions, expected}) for Laya / Clef-style typed models.

Mix.install([{:yaml_elixir, "~> 2.12"}])

root = Path.expand("..", __DIR__)
Code.require_file("data/templates/vocab.exs", root)
Code.require_file("data/templates/sdk_rules.exs", root)
Code.require_file("data/templates/sql_rules.exs", root)

defmodule Variants do
  @moduledoc """
  Label-preserving surface variation, so the model can't key on formatting.
  Variant 0 is always the original rendering.
  """

  @sql_keywords ~w(create policy table on for select insert update delete all to using with check
                   alter enable row level security function returns language as begin end if then
                   raise exception return new trigger references not null and or in exists from where
                   set search_path stable sql plpgsql replace view)

  def expand(s, n) do
    [s | for(i <- 1..(n - 1)//1, do: vary(s, i))]
    |> Enum.map(fn v -> %{v | id: :erlang.phash2({v.rule, v.state}) |> Integer.to_string(16)} end)
  end

  defp vary(s, i) do
    :rand.seed(:exsss, {:erlang.phash2(s.state), i, 7})
    [header, code] = String.split(s.state, "\n---\n", parts: 2)
    lang = if String.starts_with?(header, "Language: SQL"), do: :sql, else: :ts
    %{s | state: header <> "\n---\n" <> transform(lang, code)}
  end

  defp transform(:sql, code) do
    code
    |> maybe(0.5, &upcase_keywords/1)
    |> maybe(0.4, &String.replace(&1, "public.", ""))
    |> maybe(0.3, &(&1 <> "\n" <> Enum.random(sql_extras())))
    |> maybe(0.3, &(Enum.random(sql_comments()) <> "\n" <> &1))
  end

  defp transform(:ts, code) do
    alias_name = Enum.random(~w(client sb db supabaseClient))

    code
    |> maybe(0.6, &rename_admin/1)
    |> maybe(0.5, &rename_client(&1, alias_name))
    |> maybe(0.4, &String.replace(&1, "'", "\""))
    |> maybe(0.3, &add_semicolons/1)
    |> maybe(0.2, &("// " <> Enum.random(ts_comments()) <> "\n" <> &1))
  end

  defp maybe(x, p, f), do: if(:rand.uniform() < p, do: f.(x), else: x)

  defp upcase_keywords(code) do
    Regex.replace(~r/\b(#{Enum.join(@sql_keywords, "|")})\b/, code, &String.upcase/1)
  end

  # `supabase` is the client variable in every template; `@supabase/` imports stay intact.
  defp rename_client(code, name) do
    code
    |> String.replace(~r/(?<![@\w\/.-])supabase(?=[\s.,)}]|$)/m, name)
    |> String.replace("{ supabase }", "{ supabase: #{name} }")
  end

  # Add `;` to statement ends only: never before a chained `.call` line, never on a lone
  # closing brace (it may close an object member), never after an opener.
  # Real Edge Functions often call the service-role client `supabase` / `supabaseAdmin`.
  defp rename_admin(code) do
    if String.contains?(code, "const admin =") and not String.contains?(code, "const supabase") do
      name = Enum.random(~w(supabase supabaseAdmin serviceClient))
      Regex.replace(~r/\badmin\b(?=\s*=|\.)/, code, name)
    else
      code
    end
  end

  defp add_semicolons(code) do
    lines = String.split(code, "\n")
    nexts = tl(lines) ++ [""]

    lines
    |> Enum.zip(nexts)
    |> Enum.map_join("\n", fn {line, next} ->
      t = String.trim_trailing(line)
      lead = String.trim_leading(t)

      skip =
        t == "" or lead in ["}", "})"] or
          String.ends_with?(t, ["{", "(", ",", ";", "=>", "[", ".", "=", "?", ":"]) or
          String.match?(lead, ~r/^(\/\/|if\b|for\b|else\b|}\s*else)/) or
          String.starts_with?(String.trim_leading(next), [".", "?", ":"])

      if skip, do: line, else: t <> ";"
    end)
  end

  defp sql_extras do
    [
      "create index on public.audit_log (created_at);",
      "grant select on public.plans to anon, authenticated;",
      "comment on schema public is 'application schema';",
      "create index if not exists idx_created_at on public.events (created_at desc);"
    ]
  end

  defp sql_comments do
    ["-- migration generated by supabase db diff", "-- RLS setup", "-- see docs/security.md", "-- v2 schema"]
  end

  defp ts_comments do
    ["TODO: add tests", "handles form submission", "see README for setup", "server-only code"]
  end
end

defmodule GenDataset do
  alias Tpl.Vocab

  @templates [
    Tpl.ServerTrustsGetSession,
    Tpl.GetSessionHelpers,
    Tpl.FactPairs,
    Tpl.EfServiceRoleTrustsBodyIdentity,
    Tpl.AdminClientForUserScopedWork,
    Tpl.SingleWhereMaybeSingle,
    Tpl.PolicyAuthenticatedNotAuthorized,
    Tpl.SelectTrueOnPrivateData,
    Tpl.UserMetadataForAuthorization,
    Tpl.DefinerFunctionNoCallerCheck
  ]

  # One family per rule never appears in training: measures generalisation to new phrasing.
  @holdout %{
    "server-trusts-getsession" => "user-id-param",
    "ef-service-role-trusts-body-identity" => "delete-by-email",
    "admin-client-for-user-scoped-work" => "own-profile-update",
    "single-where-maybe-single" => "optional-settings",
    "policy-authenticated-not-authorized" => "insert-any-owner",
    "select-true-on-private-data" => "anon-auth-true",
    "user-metadata-for-authorization" => "helper-is-admin",
    "definer-function-no-caller-check" => "set-role"
  }
  # fact-pair families hold out by table (unseen tables in test) rather than by family

  def run(argv, root) do
    {opts, _} = OptionParser.parse!(argv, strict: [out: :string, val_frac: :float, variants: :integer])
    out = Path.expand(Keyword.get(opts, :out, "data/generated"), root)
    val_frac = Keyword.get(opts, :val_frac, 0.1)
    variants = Keyword.get(opts, :variants, 3)

    rules = load_rules(Path.join(root, "rules"))
    missing = Enum.uniq(Enum.flat_map(@templates, &(if function_exported?(&1, :rules, 0), do: &1.rules(), else: [&1.rule()]))) -- Map.keys(rules)
    if missing != [], do: raise("templates without rule yaml: #{inspect(missing)}")

    samples =
      @templates
      |> Enum.flat_map(&render/1)
      |> Enum.flat_map(&Variants.expand(&1, variants))
      |> Enum.uniq_by(&{&1.rule, &1.state})
      |> Enum.map(&assign_split(&1, val_frac))

    File.mkdir_p!(out)

    for split <- ~w(train val test) do
      rows = Enum.filter(samples, &(&1.split == split))
      write_jsonl(Path.join(out, "#{split}.jsonl"), rows)
      write_jsonl(Path.join(out, "typed_#{split}.jsonl"), Enum.map(rows, &typed(&1, rules)))
    end

    print_stats(samples)
  end

  defp load_rules(dir) do
    dir
    |> Path.join("*.yaml")
    |> Path.wildcard()
    |> Map.new(fn path ->
      rule = YamlElixir.read_from_file!(path)
      {rule["id"], rule}
    end)
  end

  defp render(mod) do
    case mod.kind() do
      :server ->
        for r <- Vocab.resources(),
            fw <- Vocab.frameworks(r),
            {family, label, body} <- mod.render(r, fw) do
          sample(mod, family, label, r, fw.id, Vocab.ts_header(fw.context, fw.file), fw.wrap.(body))
        end

      :fact_pairs ->
        for r <- Vocab.resources(), {rule, family, label, file, context, code, facts} <- mod.render(r) do
          header = Vocab.ts_header(context, file) <> "\nFacts: " <> Enum.join(facts, "; ")
          %{sample(mod, family, label, r, "fact-pairs", header, code) | rule: rule}
          |> then(&%{&1 | id: :erlang.phash2({rule, &1.state}) |> Integer.to_string(16), base: {rule, family, r.table, label}})
        end

      :standalone ->
        for r <- Vocab.resources(), {family, label, file, context, code} <- mod.render(r) do
          sample(mod, family, label, r, "standalone", Vocab.ts_header(context, file), code)
        end

      :edge ->
        for r <- Vocab.resources(), {family, label, body} <- mod.render(r) do
          file = "supabase/functions/#{String.replace(r.noun, "_", "-")}-handler/index.ts"
          header = Vocab.ts_header("edge function (Supabase Edge Function, Deno)", file)
          sample(mod, family, label, r, "edge", header, Vocab.edge_wrap(body))
        end

      :sql ->
        private =
          for r <- Vocab.resources(), {family, label, sql} <- mod.render(r) do
            header = Vocab.sql_header(Tpl.Sql.file(r, family), "Table public.#{r.table} holds per-user data.")
            sample(mod, family, label, r, "sql", header, sql)
          end

        public =
          if function_exported?(mod, :render_public, 1) do
            for p <- Vocab.public_resources(), {family, label, sql} <- mod.render_public(p) do
              header = Vocab.sql_header(Tpl.Sql.file(p, family), "Table public.#{p.table} holds shared data.")
              sample(mod, family, label, p, "sql", header, sql)
            end
          else
            []
          end

        private ++ public
    end
  end

  defp sample(mod, family, label, r, framework, header, code) do
    state = header <> "\n---\n" <> String.trim(code) <> "\n"

    %{
      id: :erlang.phash2({mod.rule(), state}) |> Integer.to_string(16),
      base: {mod.rule(), family, r.table, framework, label},
      rule: mod.rule(),
      family: family,
      label: label,
      resource: r.table,
      resource_split: r.split,
      framework: framework,
      state: state
    }
  end

  defp assign_split(s, val_frac) do
    split =
      cond do
        s.resource_split == :test -> "test"
        @holdout[s.rule] == s.family -> "test"
        :erlang.phash2(s.base, 1000) < val_frac * 1000 -> "val"
        true -> "train"
      end

    s |> Map.put(:split, split) |> Map.drop([:resource_split, :base])
  end

  defp typed(s, rules) do
    q = rules[s.rule]["question"]

    %{
      id: s.id,
      state: s.state,
      questions: %{s.rule => q},
      expected: %{s.rule => if(s.label == 1, do: "true", else: "false")}
    }
  end

  defp write_jsonl(path, rows) do
    File.write!(path, Enum.map_join(rows, "", &(JSON.encode!(&1) <> "\n")))
  end

  defp print_stats(samples) do
    IO.puts(String.pad_trailing("rule", 40) <> "  train(+/-)   val(+/-)    test(+/-)")

    samples
    |> Enum.group_by(& &1.rule)
    |> Enum.sort()
    |> Enum.each(fn {rule, rows} ->
      cols =
        for split <- ~w(train val test) do
          in_split = Enum.filter(rows, &(&1.split == split))
          pos = Enum.count(in_split, &(&1.label == 1))
          String.pad_trailing("#{length(in_split)}(#{pos}/#{length(in_split) - pos})", 12)
        end

      IO.puts(String.pad_trailing(rule, 40) <> "  " <> Enum.join(cols))
    end)

    IO.puts("total: #{length(samples)}")
  end
end

GenDataset.run(System.argv(), root)
